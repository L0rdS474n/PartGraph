def _make_scripted_run(  # noqa: PLR0913 — one keyword-only knob per scriptable outcome.
    *,
    initial_rows: list[dict],
    mounts_by_id: dict[str, list[dict]] | None = None,
    unit_lines: list[str] | None = None,
    ps_stdout_override: str | None = None,
    stop_returncode: int = 0,
    stop_fails_ids: frozenset[str] = frozenset(),
    ps_raises_on_call_index: int | None = None,
    inspect_fails_ids_by_pass: dict[int, frozenset[str]] | None = None,
):
    """Return (fake_run, calls) — a STATEFUL subprocess.run stand-in.

    ``fake_run`` dispatches on argv shape (never trusts call ORDER). ``live``
    is the in-memory {container_id: row} set. A successful engine `stop`
    (target NOT in ``stop_fails_ids``) flips that row's ``State`` to
    ``"exited"`` — it is NEVER popped/removed from ``live``. `db down`'s
    locked verb surface is `stop`-only (never `rm`): a real engine still
    LISTS a stopped container under `ps --all` in state ``exited``; modelling
    a successful stop as full removal is `rm` semantics, a modelling error
    (this is the same category of bug GATE-PR7 A18 fixed — asserting a
    container must not EXIST rather than must not be RUNNING). So a SECOND
    `ps` call (a verification re-enumeration) STILL lists a stopped
    container — it just carries a NOT_RUNNING status now, exactly like a
    real engine — and STILL triggers a fresh `container inspect` call on it
    (the row is not gone), which is what makes "survived the stop" and "was
    stopped" genuinely distinguishable, mirroring
    tests/unit/test_cli_db_down.py's `_make_scripted_run` (Gate 3a finding
    3a-M6 / Gate 6 fixture-premise fix). ``ps_stdout_override`` lets a test
    replace the ps response body verbatim (empty string / malformed text /
    an oversized payload) for every ps call. ``calls`` records every (argv,
    kwargs) pair in order.

    ``inspect_fails_ids_by_pass`` (Gate 5 finding A) maps a 1-indexed `ps`
    PASS NUMBER (1 = the first `find_partgraph_instances()` call a test
    makes — e.g. `stop_all()`'s pre-stop sweep; 2 = a SECOND call — e.g.
    `stop_all()`'s verification re-enumeration) to the set of container ids
    whose `container inspect` call should FAIL (non-zero exit) during that
    specific pass, so "fails on both passes" vs "only during verification"
    vs "only during the pre-stop sweep" are all independently scriptable.
    """
    mounts_by_id = mounts_by_id or {}
    unit_lines = unit_lines if unit_lines is not None else _UNIT_NOT_FOUND_LINES
    inspect_fails_ids_by_pass = inspect_fails_ids_by_pass or {}
    # `.get("Id") or .get("ID")` (never a bare `row["Id"]`): this fixture's
    # OWN bookkeeping key must accept a Docker-shaped row (id key spelled
    # 'ID') exactly like the production `_row_id()` it is standing in for —
    # otherwise a Docker-shaped `initial_rows` entry raises `KeyError`
    # before the scenario under test even runs. Backward compatible: every
    # existing caller here only ever sets "Id", so this is additive.
    live: dict[str, dict] = {
        (row.get("Id") or row.get("ID")): row for row in initial_rows
    }
    calls: list[tuple[list[str], dict]] = []
    ps_call_count = 0

    def _fake(argv, **kwargs):  # noqa: PLR0911 — one branch per scriptable verb.
        nonlocal ps_call_count
        calls.append((list(argv), dict(kwargs)))
        if _is_systemctl_show_call(argv):
            return _Proc(stdout="\n".join(unit_lines))
        if _is_systemctl_stop_call(argv):
            return _Proc(returncode=0)
        if _is_inspect_call(argv):
            cid = argv[-1]
            failing_ids = inspect_fails_ids_by_pass.get(ps_call_count, frozenset())
            if cid in failing_ids:
                return _Proc(returncode=1, stderr="inspect failed")
            return _Proc(stdout=json.dumps([{"Id": cid, "Mounts": mounts_by_id.get(cid, [])}]))
        if _is_ps_call(argv):
            ps_call_count += 1
            if ps_raises_on_call_index == ps_call_count:
                raise subprocess.TimeoutExpired(cmd=argv, timeout=10)
            if ps_stdout_override is not None:
                return _Proc(stdout=ps_stdout_override)
            return _Proc(stdout=json.dumps(list(live.values())))
