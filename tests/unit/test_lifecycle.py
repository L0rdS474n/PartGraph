def _ps_row(container_id: str, name: str, image: str, *, state: str = "running",
            host_ports: tuple[int, ...] = ()) -> dict:
    """Build one canonical `<engine> ps --all --format json` row.

    A single, consistent per-row schema is used for BOTH the JSON-array and
    the NDJSON fixtures in this file: the LIVE-VERIFIED unknown is the OUTER
    envelope shape (array vs newline-delimited), not the per-row field names.
    """
    return {
        "Id": container_id,
        "Names": [name],
        "Image": image,
        "State": state,
        "Ports": [
            {
                "host_ip": "127.0.0.1",
                "host_port": p,
                "container_port": 8080,
                "protocol": "tcp",
            }
            for p in host_ports
        ],
    }


def _mounts(*volume_names: str, destination: str = "/dgraph") -> list[dict]:
    """Build a `container inspect --format json` `.Mounts` fixture."""
    return [
        {"Type": "volume", "Name": v, "Destination": destination}
        for v in volume_names
    ]


def _docker_ports_string(*host_ports: int, container_port: int = 8080,
                          protocol: str = "tcp", host_ip: str = "0.0.0.0") -> str:
    """Build a Docker-style comma-joined `Ports` string, e.g.
    "0.0.0.0:8081->8080/tcp, 0.0.0.0:9081->8080/tcp" — mirrors the EXACT
    shape `docker ps --format json` reports (Gate 5 finding B), distinct
    from podman's `list[dict]` shape `_ps_row` builds by default.
    """
    return ", ".join(f"{host_ip}:{p}->{container_port}/{protocol}" for p in host_ports)


def _ps_row_with_ports_field(container_id: str, name: str, image: str, *,
                              state: str = "running", ports_field: object) -> dict:
    """Like `_ps_row`, but with an EXPLICIT, already-shaped `Ports` value —
    a Docker-style string, a malformed string, or an empty string (Gate 5
    finding B; podman's `list[dict]` shape is already covered by `_ps_row`
    itself).
    """
    return {
        "Id": container_id,
        "Names": [name],
        "Image": image,
        "State": state,
        "Ports": ports_field,
    }


class _Proc:
    """Minimal stand-in for subprocess.CompletedProcess."""

    def __init__(self, *, stdout: str = "", stderr: str = "", returncode: int = 0) -> None:
        self.stdout = stdout
        self.stderr = stderr
        self.returncode = returncode


def _is_ps_call(argv: list[str]) -> bool:
    return "ps" in argv and "--all" in argv


def _is_inspect_call(argv: list[str]) -> bool:
    return "container" in argv and "inspect" in argv


def _is_engine_stop_call(argv: list[str]) -> bool:
    return bool(argv) and argv[0] != "systemctl" and "stop" in argv and "compose" not in argv


def _is_systemctl_show_call(argv: list[str]) -> bool:
    return bool(argv) and argv[0] == "systemctl" and "show" in argv


def _is_systemctl_stop_call(argv: list[str]) -> bool:
    return bool(argv) and argv[0] == "systemctl" and "stop" in argv and "show" not in argv


